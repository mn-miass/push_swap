#include "../push_swap.h"

void    rb(t_list **b)
{
    t_list  *tmp;

    tmp = *b;
    while (tmp -> next)
        tmp = tmp -> next;
    tmp -> next = *b;
    *b = (*b) -> next;
    (tmp -> next) -> next = NULL;
}
